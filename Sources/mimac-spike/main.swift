import Foundation
import MimacCore

private struct Options {
    var writeReport: String?
    var pilotSeconds: TimeInterval?
    var live = false
    var powerKeySeconds: Int?

    static func parse(_ arguments: [String]) -> Options? {
        var options = Options()
        var index = 1
        while index < arguments.count {
            switch arguments[index] {
            case "--report":
                guard index + 1 < arguments.count else { return nil }
                options.writeReport = arguments[index + 1]
                index += 2
            case "--pilot-seconds":
                guard index + 1 < arguments.count,
                      let seconds = TimeInterval(arguments[index + 1]), seconds >= 10 else { return nil }
                options.pilotSeconds = seconds
                index += 2
            case "--power-keys":
                guard index + 1 < arguments.count, let seconds = Int(arguments[index + 1]), seconds > 0 else { return nil }
                options.powerKeySeconds = seconds
                index += 2
            case "--live":
                options.live = true
                index += 1
            case "--help", "-h":
                return nil
            default:
                return nil
            }
        }
        return options
    }
}

private func collectProbes() -> [ProbeResult] {
    var results = CoreProbes.run()
    results.append(CoalitionProbe.run())
    results.append(GasGauge.probe())
    results.append(SMCProbe.probe())
    let gpu = GPUProbe.probe()
    results.append(contentsOf: [gpu.0, gpu.1])
    results.append(MiscProbes.network())
    results.append(MiscProbes.frontmost())
    results.append(MiscProbes.powerAssertions())
    results.append(MiscProbes.thermal())
    results.append(MiscProbes.memoryPressure())
    results.append(MiscProbes.brightness())
    results.append(MiscProbes.powerEvents())
    results.append(ProbeResult(
        id: 22,
        metric: "Reference instrument (calibration only)",
        api: "powermetrics",
        verdict: .estimable,
        detail: "manual root-only reference; intentionally not a runtime dependency",
        evidence: ["Run powermetrics manually during controlled calibration; the spike does not invoke sudo."]
    ))
    return results.sorted { $0.id < $1.id }
}

private func printTable(_ results: [ProbeResult]) {
    print("\nStage 0 telemetry feasibility\n")
    print("#   " + pad("Metric", 43) + " " + pad("Verdict", 11) + " Detail")
    print(String(repeating: "-", count: 112))
    for result in results {
        print(pad(String(result.id), 3, right: true) + " " + pad(result.metric, 43) + " " + pad(result.verdict.rawValue, 11) + " " + result.detail)
    }
    let measured = results.filter { $0.verdict == .measured }.count
    let estimable = results.filter { $0.verdict == .estimable }.count
    let unavailable = results.filter { $0.verdict == .unavailable }.count
    print("\nSummary: \(measured) measured, \(estimable) estimable, \(unavailable) unavailable")
}

private func markdownReport(_ results: [ProbeResult], pilot: EnergyPilotResult?) -> String {
    let formatter = ISO8601DateFormatter()
    var lines = [
        "# Mimac Stage 0 Feasibility Report",
        "",
        "> Generated by `mimac-spike` on \(formatter.string(from: Date())). Re-run on each target macOS release.",
        "",
        "## Environment",
        "",
    ]
    lines.append(contentsOf: MachineInfo.summary().map { "- \($0)" })
    lines += [
        "",
        "## Telemetry matrix",
        "",
        "| # | Metric | Plain user | Privileged helper | Value quality |",
        "|---:|---|---|---|---|",
    ]
    for result in results {
        let detail = result.detail.replacingOccurrences(of: "|", with: "\\|")
        lines.append("| \(result.id) | \(result.metric) | **\(result.verdict.rawValue)** | Not run | \(detail) |")
    }
    lines += ["", "## Evidence", ""]
    for result in results {
        lines.append("### \(result.id). \(result.metric)")
        lines.append("")
        lines.append("- API: `\(result.api)`")
        lines.append("- Verdict: **\(result.verdict.rawValue)**")
        for evidence in result.evidence {
            lines.append("- \(evidence)")
        }
        lines.append("")
    }
    lines += ["## Energy pilot", ""]
    if let pilot {
        lines.append(String(format: "- Duration: %.1f seconds (%d gas-gauge samples)", pilot.duration, pilot.samples))
        lines.append(String(format: "- Gas-gauge discharge energy: %.3f J", pilot.gaugeJoules))
        lines.append(String(format: "- Sum of readable process-energy deltas: %.3f J", pilot.processJoules))
        lines.append(String(format: "- Measured process coverage: %.1f%%", pilot.measuredCoverage * 100))
        lines.append(String(format: "- Residual (display, radios, kernel, unmetered work): %.3f J", pilot.residualJoules))
        if let error = pilot.reconciliationError {
            lines.append(String(format: "- Raw process-only reconciliation error: %.1f%% (diagnostic only; residual buckets are not modeled in Stage 0)", error * 100))
        }
    } else {
        lines.append("Not run. Use `swift run mimac-spike --pilot-seconds 3600 --report FEASIBILITY.md` while unplugged for the required one-hour pilot.")
    }
    lines += [
        "",
        "## Gate status",
        "",
        "**Stage 0 remains open.** This run covers the plain-user API matrix. Before declaring GO, run the one-hour unplugged pilot, record privileged-helper results where a plain-user probe failed, and review criterion 3 against the measured evidence.",
        "",
    ]
    return lines.joined(separator: "\n")
}

private func printLiveTable() {
    print("\nLive power table — Ctrl-C to stop")
    print(pad("Time", 10) + pad("Battery", 13) + pad("GPU", 9) + pad("Thermal", 12) + "Top process CPU energy counter")
    while true {
        let battery = GasGauge.sample().map { String(format: "%.2f W", abs($0.watts)) } ?? "n/a"
        let gpu = GPUProbe.deviceUtilization().map { String(format: "%.0f%%", $0) } ?? "n/a"
        let thermalNames: [ProcessInfo.ThermalState: String] = [.nominal: "nominal", .fair: "fair", .serious: "serious", .critical: "critical"]
        let thermal = thermalNames[ProcessInfo.processInfo.thermalState] ?? "unknown"
        let top = EnergyCensus.run().topByEnergy.first
        let topText = top.map { "\($0.0) (pid \($0.1), \(fmtJ(max($0.2, $0.3))))" } ?? "none"
        let time = DateFormatter.localizedString(from: Date(), dateStyle: .none, timeStyle: .medium)
        print(pad(time, 10) + pad(battery, 13) + pad(gpu, 9) + pad(thermal, 12) + topText)
        fflush(stdout)
        Thread.sleep(forTimeInterval: 2)
    }
}

if CommandLine.arguments.contains("--help") || CommandLine.arguments.contains("-h") {
    print("Usage: mimac-spike [--report PATH] [--pilot-seconds N] [--live]")
    print("  No flags: run every Appendix A probe once and print the feasibility table.")
    print("  --report: write the evidence and current gate status as Markdown.")
    print("  --pilot-seconds: integrate gas-gauge and process energy for at least 10 seconds.")
    print("  --power-keys N: sample every decodable SMC P* key once a second for N seconds (min/avg/max).")
    print("  --live: continue with a lightweight live power table after the probes.")
    exit(0)
}

guard let options = Options.parse(CommandLine.arguments) else {
    fputs("Invalid arguments. Run mimac-spike --help for usage.\n", stderr)
    exit(64)
}

if let seconds = options.powerKeySeconds {
    printPowerKeys(seconds: seconds)
    exit(0)
}

for line in MachineInfo.summary() { print(line) }
let results = collectProbes()
printTable(results)

var pilot: EnergyPilotResult?
if let seconds = options.pilotSeconds {
    print("\nRunning energy pilot for \(Int(seconds)) seconds. Keep the Mac unplugged for a meaningful result...")
    pilot = EnergyPilot.run(seconds: seconds)
    if let pilot {
        print(String(format: "Pilot: gauge %.3f J, processes %.3f J, coverage %.1f%%, residual %.3f J",
                     pilot.gaugeJoules, pilot.processJoules, pilot.measuredCoverage * 100, pilot.residualJoules))
    }
}

if let path = options.writeReport {
    do {
        try markdownReport(results, pilot: pilot).write(toFile: path, atomically: true, encoding: .utf8)
        print("Wrote \(path)")
    } catch {
        fputs("Could not write report: \(error)\n", stderr)
        exit(1)
    }
}

if options.live { printLiveTable() }

/// Every power-looking SMC key, sampled once a second, so rails can be matched
/// to loads by running one (CPU spin, GPU, brightness) while this records.
private func printPowerKeys(seconds: Int) {
    guard let smc = SMCReader() else { print("AppleSMC unavailable"); return }
    let keys = smc.allKeyNames().filter { $0.hasPrefix("P") }.filter { smc.value($0) != nil }
    var series: [String: [Double]] = [:]
    for _ in 0..<seconds {
        for key in keys { if let value = smc.value(key) { series[key, default: []].append(value) } }
        Thread.sleep(forTimeInterval: 1)
    }
    for key in keys.sorted() {
        guard let values = series[key], !values.isEmpty else { continue }
        let avg = values.reduce(0, +) / Double(values.count)
        print(String(format: "%@  min %9.3f  avg %9.3f  max %9.3f", key, values.min()!, avg, values.max()!))
    }
}
